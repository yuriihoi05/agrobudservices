const STORAGE_KEY = "cookie-consent";
const ACCEPTED = "accepted";

/*
 * Згода живе в localStorage — поза React, тож читаємо її через
 * useSyncExternalStore. На сервері згода вважається наданою, і банер не
 * потрапляє в HTML: інакше він блимав би на кожному завантаженні у тих,
 * хто його вже закрив.
 */

let listeners: Array<() => void> = [];

function emitChange() {
  for (const listener of listeners) listener();
}

function subscribe(onStoreChange: () => void) {
  listeners = [...listeners, onStoreChange];
  window.addEventListener("storage", onStoreChange);

  return () => {
    listeners = listeners.filter((listener) => listener !== onStoreChange);
    window.removeEventListener("storage", onStoreChange);
  };
}

const getSnapshot = () => window.localStorage.getItem(STORAGE_KEY) === ACCEPTED;
const getServerSnapshot = () => true;

function acceptCookies() {
  window.localStorage.setItem(STORAGE_KEY, ACCEPTED);
  emitChange();
}

