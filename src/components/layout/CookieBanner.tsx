/**
 * Банер про cookies. В оригіналі його показував сторонній скрипт
 * Finsweet Cookie Consent, а стилі були суперечливими: `.cookies-banner`
 * оголошував grid і тут же `display: block`, мав `margin-top: -50px` при
 * `position: fixed; bottom: 20px`, а сітка `auto minmax(200px,785px) auto`
 * ламалася на планшеті. Тут — власна реалізація без зовнішніх залежностей.
 *
 * Режим інформаційний (як `fs-cc-mode="informational"` в оригіналі): банер
 * лише повідомляє і закривається, нічого не блокуючи.
 */
export function CookieBanner() {
  const t = useTranslations("cookies");
  const isAccepted = useSyncExternalStore(subscribe, getSnapshot, getServerSnapshot);

  if (isAccepted) return null;

  return (
    <div
      role="region"
      aria-label={t("title")}
      className="fixed inset-x-5 bottom-5 z-50 mx-auto max-w-5xl rounded-lg bg-white p-5 text-ink shadow-[0_20px_50px_-10px_rgba(0,0,0,0.22)] sm:p-6"
    >
      <div className="flex flex-col items-start gap-5 sm:flex-row sm:items-center">
        <CookieIcon className="hidden size-15 shrink-0 sm:block" />

        <div className="flex-1">
          <p className="font-semibold">{t("title")}</p>
          <p className="mt-2 text-sm leading-relaxed text-grey">
            {t.rich("text", {
              link: (chunks) => (
                <Link
                  href="/privacy-policy"
                  className="focus-ring rounded-sm font-medium text-gold underline underline-offset-2 transition-colors duration-200 hover:text-gold-dark"
                >
                  {chunks}
                </Link>
              ),
            })}
          </p>
        </div>

        <button
          type="button"
          onClick={acceptCookies}
          className="focus-ring w-full shrink-0 rounded-full bg-gold px-8 py-3 text-center font-medium text-white transition-colors duration-300 hover:bg-gold-dark sm:w-auto"
        >
          {t("accept")}
        </button>
      </div>
    </div>
  );
}
