import type { Locale } from "@/i18n/routing";

/**
 * Відкриті вакансії.
 *
 * У /legacy-export/career.html списку вакансій немає взагалі — замість нього
 * стоїть текст «на даний момент вакансій у нас немає». Тобто це не втрачені
 * дані, а справжній стан сторінки на момент експорту.
 *
 * Масив порожній → сторінка показує той самий текст-заглушку з оригіналу.
 * Додайте вакансію — і замість нього автоматично зʼявиться список карток,
 * нічого в коді міняти не треба.
 */

type Localized = Record<Locale, string>;

export type Vacancy = {
  slug: string;
  title: Localized;
  /** Місто / формат роботи — короткий рядок під заголовком. */
  location: Localized;
  /** Тип зайнятості: повна, часткова тощо. */
  employment: Localized;
  /** Опис і вимоги; кожен рядок — окремий пункт списку. */
  responsibilities: Localized[];
};

export const vacancies: Vacancy[] = [];
